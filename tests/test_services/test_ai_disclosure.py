def test_interaction_from_row_reads_metadata_and_normalizes():
    naive = datetime(2026, 3, 1, 9, 0)
    record = interaction_from_row(
        session_id="abc",
        task_type=TaskType.CHAT,
        created_at=naive,
        metadata={"task": "edit", "llm_provider": "ZAI", "llm_model": " glm-4.7 ", "revision_id": "REV-1"},
        tokens_used=0,
        input_chars=12,
        output_chars=0,
    )
    assert record is not None
    assert record.task == "edit"
    assert record.legacy is False
    assert record.provider == "zai"
    assert record.model == "glm-4.7"
    assert record.revision_id == "rev-1"
    assert record.created_at.tzinfo is not None

    legacy = interaction_from_row(
        session_id="def",
        task_type=TaskType.LOGIC,
        created_at=naive,
        metadata=None,
        tokens_used=50,
        input_chars=0,
        output_chars=0,
    )
    assert legacy is not None
    assert (legacy.task, legacy.legacy) == ("logic", True)


