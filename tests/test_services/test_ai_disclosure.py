# ─── Attribution of suggestions to tasks ─────────────────────────────────────


def test_legacy_rows_are_inferred_by_time_window_and_chat_becomes_edit():
    interactions = [
        _interaction("old-style", "style", 1, legacy=True),
        _interaction("old-chat", "chat", 6, legacy=True),
        _interaction("old-chat-2", "chat", 7, legacy=True),
        _interaction("old-logic", "logic", 60.5, legacy=True),
    ]
    suggestions = [
        _suggestion("s1", "accepted", 0.9),  # → old-style
        _suggestion("s2", "rejected", 5.9),  # → old-chat, relabelled edit
        _suggestion("s3", "accepted", 60),  # logic never produces suggestions → unattributed
    ]
    attribution = attribute_suggestions(interactions, suggestions)

    assert attribution.task_by_suggestion == {"s1": "style", "s2": "edit", "s3": None}
    assert attribution.task_by_interaction["old-chat"] == "edit"
    assert attribution.task_by_interaction["old-chat-2"] == "chat"
    assert (attribution.linked, attribution.inferred, attribution.unattributed) == (0, 2, 1)

    report = _report(interactions, suggestions)
    assert [row.task for row in report.by_task] == ["style", "edit", "logic", "chat"]
    assert report.unattributed.proposed == 1
    assert report.unattributed.accepted == 1


def test_inference_ignores_interactions_outside_window_and_new_rows():
    interactions = [
        _interaction("late", "style", 30, legacy=True),  # beyond the 10-minute window
        _interaction("new-style", "style", 1),  # new rows only match by explicit revision_id
    ]
    attribution = attribute_suggestions(interactions, [_suggestion("s1", "accepted", 0)])
    assert attribution.task_by_suggestion == {"s1": None}
    assert attribution.unattributed == 1


