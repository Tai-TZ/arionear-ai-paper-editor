# ─── Text helpers / LaTeX ────────────────────────────────────────────────────


def test_escape_latex_special_characters():
    assert escape_latex("50% & $x_1$ #1 {a} \\ ~ ^ <b> |") == (
        r"50\% \& \$x\_1\$ \#1 \{a\} \textbackslash{} \textasciitilde{} \textasciicircum{} "
        r"\textless{}b\textgreater{} \textbar{}"
    )
    assert escape_latex("author's work") == "author's work"


def test_latex_snippet_escapes_model_names():
    interactions = [_interaction("i1", "style", 1, provider="openrouter", model="my_model~v2 & co")]
    report = _report(interactions, [])

    latex = report.latex.en
    lines = latex.splitlines()
    assert lines[0].startswith("% AI disclosure generated by Arionear on 2026-10-04")
    assert lines[1] == "\\section*{Declaration of generative AI and AI-assisted technologies in the writing process}"
    assert r"my\_model\textasciitilde{}v2 \& co via OpenRouter" in latex
    assert "my_model" not in latex
    assert "my_model~v2 & co" in report.statement.en  # plain statement stays unescaped
    assert "\\section*{Tuyên bố về việc sử dụng AI tạo sinh" in report.latex.vi


def test_join_list():
    assert join_list([], "en") == ""
    assert join_list(["a"], "en") == "a"
    assert join_list(["a", "b"], "en") == "a and b"
    assert join_list(["a", "b", "c"], "en") == "a, b, and c"
    assert join_list(["a", "b", "c"], "vi") == "a, b và c"
