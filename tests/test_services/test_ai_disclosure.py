T0 = datetime(2026, 3, 1, 9, 0, tzinfo=UTC)
GENERATED = datetime(2026, 10, 4, 12, 0, tzinfo=UTC)


def _interaction(
    iid: str,
    task: str,
    minutes: float,
    *,
    provider: str | None = "zai",
    model: str | None = "glm-4.7-flash",
    revision_id: str | None = None,
    legacy: bool = False,
) -> InteractionRecord:
    return InteractionRecord(
        id=iid,
        task=task,
        created_at=T0 + timedelta(minutes=minutes),
        provider=provider,
        model=model,
        revision_id=revision_id,
        legacy=legacy,
    )


def _suggestion(sid: str, status: str, minutes: float) -> SuggestionRecord:
    return SuggestionRecord(id=sid, status=status, created_at=T0 + timedelta(minutes=minutes))


def _report(interactions, suggestions):
    return build_ai_disclosure_report(
        paper_id="paper-1",
        paper_title="My Paper",
        interactions=interactions,
        suggestions=suggestions,
        generated_at=GENERATED,
    )


def _task_row(report, task):
    return next(row for row in report.by_task if row.task == task)


# ─── No AI usage ─────────────────────────────────────────────────────────────


def test_no_ai_usage_reports_honestly():
    report = _report([], [])

    assert report.has_ai_usage is False
    assert report.totals.interactions == 0
    assert report.totals.proposed == 0
    assert report.by_task == []
    assert report.models == []
    assert report.period.first_interaction_at is None
    assert report.period.last_interaction_at is None
