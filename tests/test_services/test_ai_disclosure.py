# ─── Mixed accept / reject ───────────────────────────────────────────────────


def test_mixed_accept_reject_counts_and_statement():
    interactions = [
        _interaction("i1", "style", 1, revision_id="s1"),
        _interaction("i2", "style", 2, revision_id="s2"),
        _interaction("i3", "edit", 3, revision_id="s3"),
        _interaction("i4", "edit", 4, revision_id="s4"),
        _interaction("i5", "edit", 5, revision_id="s5"),
    ]
    suggestions = [
        _suggestion("s1", "accepted", 0.5),
        _suggestion("s2", "rejected", 1.5),
        _suggestion("s3", "modified", 2.5),
        _suggestion("s4", "accepted", 3.5),
        _suggestion("s5", "pending", 4.5),
    ]
    report = _report(interactions, suggestions)

    assert report.has_ai_usage is True
    totals = report.totals
    assert (totals.interactions, totals.proposed) == (5, 5)
    assert (totals.accepted, totals.modified, totals.rejected, totals.pending) == (2, 1, 1, 1)
    assert report.attribution.model_dump() == {"linked": 5, "inferred": 0, "unattributed": 0}

    style = _task_row(report, "style")
    assert (style.interactions, style.proposed, style.accepted, style.rejected) == (2, 2, 1, 1)
    edit = _task_row(report, "edit")
    assert (edit.interactions, edit.proposed, edit.accepted, edit.modified, edit.pending) == (3, 3, 1, 1, 1)

    en = report.statement.en
    assert "Arionear proposed 5 text revisions" in en
    assert "3 accepted (1 after modification by the author(s)), 1 rejected, and 1 left undecided." in en
    assert "None of the AI-proposed revisions" not in en
    assert "take(s) full responsibility for the content of the publication" in en

    vi = report.statement.vi
    assert "Arionear đã đề xuất 5 chỉnh sửa văn bản" in vi
    assert "3 được chấp nhận (trong đó 1 được tác giả sửa lại trước khi chấp nhận), 1 bị từ chối" in vi
    assert "1 chưa được quyết định" in vi
    assert "chịu hoàn toàn trách nhiệm" in vi

    assert report.period.first_interaction_at == T0 + timedelta(minutes=0.5)
    assert report.period.last_interaction_at == T0 + timedelta(minutes=5)


def test_nothing_accepted_is_stated_explicitly():
    interactions = [_interaction("i1", "style", 1, revision_id="s1"), _interaction("i2", "style", 2)]
    suggestions = [_suggestion("s1", "rejected", 0.5)]
    report = _report(interactions, suggestions)

    assert report.totals.accepted == 0
    assert "Arionear proposed 1 text revision," in report.statement.en
    assert "0 accepted and 1 rejected." in report.statement.en
    assert "None of the AI-proposed revisions were accepted into the manuscript." in report.statement.en
    assert "Không có đề xuất chỉnh sửa nào của AI được đưa vào bản thảo." in report.statement.vi


