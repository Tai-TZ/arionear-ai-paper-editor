# ─── Task types ──────────────────────────────────────────────────────────────


def test_multiple_task_types_only_mentions_tasks_that_occurred():
    interactions = [
        _interaction("i1", "logic", 1),
        _interaction("i2", "citation", 2),
        _interaction("i3", "style", 3, revision_id="s1"),
        _interaction("i4", "citation", 4),
    ]
    suggestions = [_suggestion("s1", "accepted", 2.9)]
    report = _report(interactions, suggestions)

    # Canonical order, not chronological order.
    assert [row.task for row in report.by_task] == ["style", "citation", "logic"]
    assert _task_row(report, "citation").interactions == 2

    en = report.statement.en
    assert (
        "to improve the language, grammar and style of selected passages, check and verify bibliographic "
        "references, and audit the logical consistency of the argumentation." in en
    )
    for absent in ("template", "structure of the manuscript", "answer questions", "draft and revise"):
        assert absent not in en

    vi = report.statement.vi
    assert "kiểm tra và xác minh tài liệu tham khảo và rà soát tính nhất quán logic của lập luận." in vi
    assert "khung mẫu LaTeX" not in vi


def test_models_are_deduplicated_and_described():
    interactions = [
        _interaction("i1", "chat", 1, provider="zai", model="glm-4.7-flash"),
        _interaction("i2", "chat", 2, provider="zai", model="glm-4.7-flash"),
        _interaction("i3", "chat", 3, provider="google", model=None),
        _interaction("i4", "chat", 4, provider=None, model=None),
    ]
    report = _report(interactions, [])

    assert [(m.provider, m.model, m.interactions) for m in report.models] == [
        ("zai", "glm-4.7-flash", 2),
        ("google", None, 1),
    ]
    assert report.models[1].provider_label == "Google Gemini"
    assert "(models: glm-4.7-flash via Z.AI GLM and Google Gemini)" in report.statement.en
    assert "(mô hình: glm-4.7-flash qua Z.AI GLM và Google Gemini)" in report.statement.vi


