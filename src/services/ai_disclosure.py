"""AI Contribution Report ("AI disclosure") for a paper — deterministic, no LLM call.

Data sources (persisted PostgreSQL tables, the authoritative record):

- ``ai_sessions`` rows written by :func:`src.services.usage_tracking.record_ai_usage` after every
  streamed AI interaction: task type, timestamp and LLM provider/model (``metadata``). Newer rows
  also carry the raw task name (``metadata.task`` — ``TaskType`` has no ``EDIT`` member, so edits
  used to be stored as ``CHAT``) and the revision they produced (``metadata.revision_id``).
  Empty placeholder rows created when a paper is initialised are ignored.
- ``suggestions`` rows: the diff-based revisions the author accepts or rejects in the editor.

The in-memory session store is a no-database dev fallback without auth or usage tracking, so the
report never reads it (the papers API already requires a database). ``audit_logs`` is not written
by any code path today, so ``suggestions.status`` is the source of truth for accept/reject.

Everything below the "DB loading" section is pure and unit-testable without a database.
"""

from __future__ import annotations

